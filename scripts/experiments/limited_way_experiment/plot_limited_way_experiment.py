#!/usr/bin/env python3
"""
Plot wrapper for the limited-way single-core experiment.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Optional, Sequence

SCRIPT_DIR = Path(__file__).resolve().parent.parent.parent
REPO_ROOT = SCRIPT_DIR.parents[0]

if str(REPO_ROOT) not in sys.path:
    sys.path.append(str(REPO_ROOT))

from scripts.experiments.single_core_performance.plot_single_core_metrics import (  # type: ignore
    main as plot_single_core_main,
)


DEFAULT_PREFETCHERS = [
    "no",
    "gaze",
    "bingo_streaming_disable_overlap_pht_16x64",
    "step",
]


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot limited-way single-core metrics.")
    parser.add_argument(
        "--metrics",
        type=Path,
        default=None,
        help="CSV file generated by collect_metrics.py. If omitted, select by --reserved-ways.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Directory to write the generated figures. Defaults to figures/ways_<N>.",
    )
    parser.add_argument(
        "--prefetchers",
        nargs="*",
        default=DEFAULT_PREFETCHERS,
        help="Subset of prefetchers to include.",
    )
    parser.add_argument("--exclude", nargs="*", default=["no"], help="Prefetchers to exclude from top-program selection.")
    parser.add_argument("--programs", nargs="*", help="Explicit list of program short-names to plot.")
    parser.add_argument(
        "--program-categories",
        nargs="*",
        help="Benchmark categories whose programs should be emphasised in per-program plots.",
    )
    parser.add_argument("--top-programs", type=int, default=40, help="Number of programs to show by default.")
    parser.add_argument("--program-sample-seed", type=int, default=4, help="Random seed for default program sampling.")
    parser.add_argument("--cache-prefix", default="cpu0_L2C", help="Cache prefix used for prefetch statistics.")
    parser.add_argument("--run-prefix", default=None, help="Optional run prefix to plot (e.g., lw).")
    parser.add_argument(
        "--reserved-ways",
        type=int,
        default=1,
        help="Reserved-way setting to plot when --metrics is omitted.",
    )
    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    if args.reserved_ways <= 0:
        raise ValueError("--reserved-ways must be > 0")

    metrics_path = args.metrics
    if metrics_path is None:
        results_dir = REPO_ROOT / "scripts" / "results_analysis" / "results"
        metrics_path = results_dir / f"limited_way_{args.reserved_ways}way_results.csv"

    output_dir = args.output_dir or (Path(__file__).resolve().parent / "figures" / f"ways_{args.reserved_ways}")

    forwarded = [
        "--metrics",
        str(metrics_path),
        "--output-dir",
        str(output_dir),
        "--cache-prefix",
        args.cache_prefix,
        "--top-programs",
        str(args.top_programs),
        "--program-sample-seed",
        str(args.program_sample_seed),
    ]

    if args.prefetchers:
        forwarded.extend(["--prefetchers", *args.prefetchers])
    if args.exclude:
        forwarded.extend(["--exclude", *args.exclude])
    if args.programs:
        forwarded.extend(["--programs", *args.programs])
    if args.program_categories:
        forwarded.extend(["--program-categories", *args.program_categories])
    if args.run_prefix is not None:
        forwarded.extend(["--run-prefix", args.run_prefix])

    return plot_single_core_main(forwarded)


if __name__ == "__main__":
    raise SystemExit(main())
