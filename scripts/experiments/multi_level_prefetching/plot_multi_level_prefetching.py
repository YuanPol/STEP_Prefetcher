#!/usr/bin/env python3
"""
Plot single-core speedups for multi-level (L1+L2) prefetcher combinations.

The figure focuses on per-trace speedup only (no benchmark-suite split).
Legend entries use the "A+B" naming where A is the L1 prefetcher and B is the
L2 prefetcher.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Optional, Sequence

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

SCRIPT_DIR = Path(__file__).resolve().parent.parent.parent
REPO_ROOT = SCRIPT_DIR.parents[0]

if str(REPO_ROOT) not in sys.path:
    sys.path.append(str(REPO_ROOT))

from scripts.results_analysis.plot_utils import (  # type: ignore
    apply_standard_style,
    ensure_dir,
    filter_prefetchers,
    load_metrics,
    _prefetcher_palette,
)

DEFAULT_METRICS = REPO_ROOT / "scripts" / "results_analysis" / "results" / "multi_level_prefetching_results.csv"

L1_PREFETCHERS = {
    "Gaze": "gaze_l1_l2_fill",
    "STEP": "step_l1_l2_fill_disable_second",
    "eBingo": "bingo_streaming_disable_overlap_l1_l2_fill",
    "vBerti": "berti",
}

L2_PREFETCHERS = {
    "Gaze": "gaze",
    "STEP": "step",
    "eBingo": "bingo_streaming_disable_overlap_pht_16x64",
    "vBerti": "berti",
}


def build_prefetchers() -> list[str]:
    names: list[str] = []
    for l1_label, l1_name in L1_PREFETCHERS.items():
        for l2_label, l2_name in L2_PREFETCHERS.items():
            if l1_label == "vBerti" and l2_label == "vBerti":
                continue
            names.append(f"{l1_name}_{l2_name}")
    names.append("ipcp_l1_ipcp_l2")
    return names


def build_prefetcher_labels() -> dict[str, str]:
    labels: dict[str, str] = {}
    for l1_label, l1_name in L1_PREFETCHERS.items():
        for l2_label, l2_name in L2_PREFETCHERS.items():
            if l1_label == "vBerti" and l2_label == "vBerti":
                continue
            labels[f"{l1_name}_{l2_name}"] = f"{l1_label}+{l2_label}"
    labels["ipcp_l1_ipcp_l2"] = "IPCP"
    return labels


PREFETCHERS = build_prefetchers()
PREFETCHER_LABELS = build_prefetcher_labels()

HATCHES = [
    "",
    "//",
    "\\\\",
    "xx",
    "..",
    "++",
    "--",
    "oo",
    "**",
    "||",
    "//",
    "\\\\",
    "xx",
    "..",
    "++",
    "--",
]


def _geometric_mean(series: pd.Series) -> float:
    cleaned = series.dropna()
    cleaned = cleaned[cleaned > 0]
    if cleaned.empty:
        return float("nan")
    return float(np.exp(np.log(cleaned).mean()))


def _select_run_prefix(df: pd.DataFrame, run_prefix: Optional[str]) -> pd.DataFrame:
    """Resolve multiple run prefixes (e.g., v00/v01) before plotting."""
    if "run_prefix" not in df.columns:
        return df

    if run_prefix:
        filtered = df[df["run_prefix"] == run_prefix].copy()
        if filtered.empty:
            available = ", ".join(sorted(str(v) for v in df["run_prefix"].dropna().unique()))
            raise ValueError(
                f"Requested run prefix '{run_prefix}' not present in metrics CSV. "
                f"Available prefixes: {available or 'none'}"
            )
        return filtered

    duplicate_mask = df.duplicated(subset=["prefetcher", "trace_base"], keep=False)
    if not duplicate_mask.any():
        return df

    ranked = df.copy()
    suffix_num = ranked["run_prefix"].astype(str).str.extract(r"(\d+)$", expand=False)
    ranked["_run_rank"] = pd.to_numeric(suffix_num, errors="coerce").fillna(-1)
    ranked = ranked.sort_values(["prefetcher", "trace_base", "_run_rank", "run_prefix"])
    deduped = ranked.drop_duplicates(subset=["prefetcher", "trace_base"], keep="last").drop(columns=["_run_rank"])
    return deduped


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Plot multi-level (L1+L2) prefetching speedups.")
    parser.add_argument(
        "--metrics",
        type=Path,
        default=DEFAULT_METRICS,
        help="CSV file generated by collect_metrics.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(__file__).resolve().parent / "figures",
        help="Directory to write the generated figure.",
    )
    parser.add_argument(
        "--run-prefix",
        default=None,
        help=(
            "Optional run prefix to plot (e.g., v01). If omitted and duplicate "
            "prefixes exist, the latest prefix per prefetcher+trace is used."
        ),
    )
    parser.add_argument(
        "--y-cap",
        type=float,
        default=1.35,
        help="Maximum y-axis value (default: 1.4).",
    )
    args = parser.parse_args(argv)

    apply_standard_style()
    df_full = load_metrics(args.metrics)
    df_full = _select_run_prefix(df_full, args.run_prefix)
    df = filter_prefetchers(df_full, PREFETCHERS)

    if df.empty:
        raise ValueError("No rows remain for the selected multi-level prefetcher combinations.")

    missing = [name for name in PREFETCHERS if name not in set(df_full["prefetcher"])]
    if missing:
        print(
            "[WARN] Missing prefetchers in metrics CSV:",
            ", ".join(missing),
            file=sys.stderr,
        )

    df = df.copy()
    df["prefetcher_label"] = df["prefetcher"].map(PREFETCHER_LABELS).fillna(df["prefetcher"])
    present_prefetchers = [name for name in PREFETCHERS if name in set(df["prefetcher"])]
    if not present_prefetchers:
        raise ValueError("None of the requested multi-level prefetchers are present in the metrics CSV.")
    ordered_labels = [PREFETCHER_LABELS[name] for name in present_prefetchers]

    output_dir = args.output_dir
    ensure_dir(output_dir)

    summary = (
        df.groupby(["prefetcher", "prefetcher_label"])["speedup"]
        .apply(_geometric_mean)
        .reset_index(name="speedup")
    )
    summary = summary.dropna(subset=["speedup"])
    summary = summary[summary["speedup"] > 0]
    if summary.empty:
        raise ValueError("No valid positive speedup values available for geometric-mean plotting.")

    prefetcher_rank = {pref: idx for idx, pref in enumerate(present_prefetchers)}
    summary["_order"] = summary["prefetcher"].map(prefetcher_rank)
    summary = summary.sort_values("_order")
    labels = summary["prefetcher_label"].tolist()
    values = summary["speedup"].to_numpy()

    palette = _prefetcher_palette(ordered_labels)

    fig_width = max(10.0, len(labels) * 0.75)
    fig, ax = plt.subplots(figsize=(fig_width, 5.6))
    x = np.arange(len(labels))
    bar_colours = [palette.get(label, "#999999") for label in labels]
    bars = ax.bar(x, values, color=bar_colours, edgecolor="black", linewidth=1.0)
    for idx, bar in enumerate(bars):
        bar.set_hatch(HATCHES[idx % len(HATCHES)])

    y_min = 1.0
    y_max = args.y_cap
    capped = np.minimum(values, y_max)
    for bar, cap_v in zip(bars, capped):
        bar.set_height(float(cap_v))
    ax.set_ylim(y_min, y_max)

    for bar, value in zip(bars, values):
        y = float(bar.get_height())
        ax.annotate(
            f"{value:.3f}",
            (bar.get_x() + bar.get_width() / 2.0, y),
            ha="center",
            va="bottom",
            fontsize=9,
            xytext=(0, 2),
            textcoords="offset points",
        )

    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.set_xlabel("Prefetcher combination (L1 + L2)")
    ax.set_ylabel("Speedup over no prefetching")
    ax.grid(axis="y", linestyle="--", linewidth=0.6, alpha=0.6)

    # legend = ax.legend(
    #     bars,
    #     labels,
    #     title="L1 + L2",
    #     loc="upper center",
    #     bbox_to_anchor=(0.5, 1.22),
    #     ncol=min(len(labels), 5),
    #     framealpha=0.95,
    # )
    # if legend is not None and legend.get_title() is not None:
    #     legend.get_title().set_fontsize(10)
    #     for text in legend.get_texts():
    #         text.set_fontsize(9)

    output_png = output_dir / "speedup_geomean_all_traces.png"
    fig.savefig(output_png, dpi=300, bbox_inches="tight")
    try:
        fig.savefig(output_png.with_suffix(".pdf"), bbox_inches="tight")
    except Exception:
        pass
    plt.close(fig)

    print(f"Wrote: {output_png}")
    try:
        print(f"Wrote: {output_png.with_suffix('.pdf')}")
    except Exception:
        pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
